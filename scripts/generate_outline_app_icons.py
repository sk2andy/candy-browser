#!/usr/bin/env python3
"""Trace the three original Candy leaves into unfilled Android vector contours.

Requires Pillow 11.3.0, numpy 2.0.2 and opencv-python-headless 5.0.0.93.
Source is the repository's unchanged Classic foreground; no OpenAI artwork is used.
"""

import hashlib
from pathlib import Path

import cv2
import numpy as np
from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app/src/main/res/drawable-nodpi/ic_launcher_foreground_art.png"
SOURCE_SHA256 = "7fd347d9eb5bb0df158f68f3382a412143144de3688f949608f69fc91a1cb8ad"


def main():
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError("Classic artwork changed: inspect it before regenerating contours")
    image = Image.open(SOURCE).convert("RGBA")
    if image.size != (432, 432):
        raise ValueError("Unexpected Classic foreground dimensions")
    mask = (np.array(image)[:, :, 3] >= 128).astype("uint8")
    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    if len(contours) != 3 or any(cv2.contourArea(c) < 10000 for c in contours):
        raise ValueError("Expected exactly three separate Candy leaves")
    contours = sorted(contours, key=lambda c: tuple(cv2.boundingRect(c)[1::-1]))
    paths = []
    for contour in contours:
        # Smooth raster stair steps with a closed Catmull-Rom curve. The complete
        # contour is retained; each sampled segment must stay near the source edge.
        points = cv2.approxPolyDP(contour, 1.5, True).reshape(-1, 2).astype(float)
        commands = [f"M{points[0][0]:.2f},{points[0][1]:.2f}"]
        for index, start in enumerate(points):
            previous = points[(index - 1) % len(points)]
            end = points[(index + 1) % len(points)]
            following = points[(index + 2) % len(points)]
            control1 = start + (end - previous) / 6
            control2 = end - (following - start) / 6
            for t in np.linspace(0, 1, 101):
                sample = ((1 - t) ** 3 * start + 3 * (1 - t) ** 2 * t * control1
                          + 3 * (1 - t) * t ** 2 * control2 + t ** 3 * end)
                if abs(cv2.pointPolygonTest(contour, tuple(sample), True)) > 2.5:
                    raise ValueError("Smoothed curve deviates from the Classic leaf")
            commands.append("C" + " ".join(
                f"{point[0]:.2f},{point[1]:.2f}" for point in (control1, control2, end)
            ))
        paths.append(" ".join(commands) + " Z")
    for variant, color in (("light", "#FF000000"), ("dark", "#FFFFFFFF")):
        xml = [
            '<?xml version="1.0" encoding="utf-8"?>',
            '<!-- Generated by scripts/generate_outline_app_icons.py from Classic alpha. -->',
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
            '    android:width="108dp" android:height="108dp"',
            '    android:viewportWidth="432" android:viewportHeight="432">',
        ]
        for path in paths:
            xml.extend([
                '    <path',
                '        android:fillColor="#00000000"',
                f'        android:strokeColor="{color}"',
                '        android:strokeWidth="8"',
                '        android:strokeLineCap="round"',
                '        android:strokeLineJoin="round"',
                f'        android:pathData="{path}" />',
            ])
        xml.append('</vector>')
        destination = ROOT / f"app/src/main/res/drawable/ic_launcher_outline_{variant}_art.xml"
        destination.write_text("\n".join(xml) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
